-- ---------------------------------------------------------------------
-- Contexto da requisição (cabeçalhos enviados pelo servidor Next.js)
-- ---------------------------------------------------------------------
create or replace function public.contexto_requisicao()
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare h json;
begin
  begin
    h := nullif(current_setting('request.headers', true), '')::json;
  exception when others then
    h := null;
  end;
  return jsonb_strip_nulls(jsonb_build_object(
    'area', left(h->>'x-geeasy-area', 30),
    'origem', coalesce(left(h->>'x-geeasy-origem', 20), case when h is not null then 'api' when auth.uid() is null then 'rotina' else 'sql' end),
    'ip', left(coalesce(h->>'x-geeasy-ip', trim(split_part(h->>'x-forwarded-for', ',', 1))), 64),
    'user_agent', left(coalesce(h->>'x-geeasy-ua', h->>'user-agent'), 300),
    'request_id', left(coalesce(h->>'x-geeasy-request-id', h->>'x-request-id'), 100)
  ));
end $$;
revoke execute on function public.contexto_requisicao() from public, anon, authenticated;

