create or replace function public.auditoria_por_funcionario(p_inicio timestamptz, p_fim timestamptz)
returns table (actor_id uuid, actor_email text, nome text, inclusoes bigint, alteracoes bigint, exclusoes bigint, restauracoes bigint,
               acessos bigint, total bigint, primeira timestamptz, ultima timestamptz)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.tem_permissao('auditoria.view') then raise exception 'Sem permissão.' using errcode = '42501'; end if;
  return query
  select a.actor_id, max(a.actor_email), max(p.full_name),
         count(*) filter (where a.acao = 'INSERT'), count(*) filter (where a.acao = 'UPDATE'),
         count(*) filter (where a.acao in ('DELETE', 'EXCLUSAO')), count(*) filter (where a.acao = 'RESTAURACAO'),
         count(*) filter (where a.acao not in ('INSERT', 'UPDATE', 'DELETE', 'EXCLUSAO', 'RESTAURACAO')),
         count(*), min(a.created_at), max(a.created_at)
    from public.audit_logs a left join public.profiles p on p.id = a.actor_id
   where a.empresa_id = public.empresa_atual() and a.created_at >= p_inicio and a.created_at < p_fim
   group by a.actor_id
   order by count(*) desc;
end $$;

create or replace function public.auditoria_por_modulo(p_actor uuid, p_inicio timestamptz, p_fim timestamptz)
returns table (tabela text, inclusoes bigint, alteracoes bigint, exclusoes bigint, acessos bigint, total bigint)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.tem_permissao('auditoria.view') then raise exception 'Sem permissão.' using errcode = '42501'; end if;
  return query
  select a.tabela, count(*) filter (where a.acao = 'INSERT'), count(*) filter (where a.acao = 'UPDATE'),
         count(*) filter (where a.acao in ('DELETE', 'EXCLUSAO')),
         count(*) filter (where a.acao not in ('INSERT', 'UPDATE', 'DELETE', 'EXCLUSAO', 'RESTAURACAO')), count(*)
    from public.audit_logs a
   where a.empresa_id = public.empresa_atual() and a.actor_id is not distinct from p_actor and a.created_at >= p_inicio and a.created_at < p_fim
   group by a.tabela order by count(*) desc;
end $$;

-- Atividade por dia da semana × hora (fuso da empresa) — comparativo entre funcionários
create or replace function public.auditoria_atividade(p_inicio timestamptz, p_fim timestamptz, p_actor uuid default null)
returns table (dia_semana int, hora int, total bigint)
language plpgsql stable security definer set search_path = '' as $$
declare v_fuso text := coalesce((select fuso from public.empresas where id = public.empresa_atual()), 'America/Sao_Paulo');
begin
  if not public.tem_permissao('auditoria.view') then raise exception 'Sem permissão.' using errcode = '42501'; end if;
  return query
  select extract(isodow from a.created_at at time zone v_fuso)::int, extract(hour from a.created_at at time zone v_fuso)::int, count(*)
    from public.audit_logs a
   where a.empresa_id = public.empresa_atual() and a.created_at >= p_inicio and a.created_at < p_fim and (p_actor is null or a.actor_id = p_actor)
   group by 1, 2 order by 1, 2;
end $$;

-- ---------------------------------------------------------------------
-- Alertas (rotina a cada 10 min): exclusões em massa, exportações, mudanças de acesso, fora do horário
-- Parâmetros em configuracoes 'alertas_auditoria': { ativos, exclusoes_limite, horario_inicio, horario_fim }
-- ---------------------------------------------------------------------
create or replace function public.auditoria_alertas()
returns int language plpgsql security definer set search_path = '' as $$
declare e record; n int := 0; k int; v_cfg jsonb; v_lim int; v_ini time; v_fim time;
begin
  for e in select id, fuso from public.empresas where status in ('trial', 'ativa') loop
    select valor into v_cfg from public.configuracoes where empresa_id = e.id and chave = 'alertas_auditoria';
    continue when coalesce((v_cfg->>'ativos')::boolean, true) = false;
    v_lim := greatest(3, coalesce((v_cfg->>'exclusoes_limite')::int, 20));
    v_ini := coalesce((v_cfg->>'horario_inicio')::time, '07:00');
    v_fim := coalesce((v_cfg->>'horario_fim')::time, '20:00');

    with eventos as (
      select a.* from public.audit_logs a where a.empresa_id = e.id and a.created_at > now() - interval '15 minutes' and a.actor_id is not null
    ), alertas as (
      select 'exclusao:' || x.actor_id || ':' || to_char(now() at time zone e.fuso, 'YYYYMMDDHH24') as chave,
             'Exclusões em massa' as titulo, coalesce(max(x.actor_email), 'Usuário') || ' excluiu ' || count(*) || ' registro(s) em 15 minutos' as msg
        from eventos x where x.acao in ('DELETE', 'EXCLUSAO') group by x.actor_id having count(*) >= v_lim
      union all
      select 'export:' || x.id, 'Exportação de dados', coalesce(x.actor_email, 'Usuário') || ' exportou ' || x.tabela || coalesce(' (' || (x.dados_novos->>'linhas') || ' linhas)', '')
        from eventos x where x.acao in ('EXPORTACAO', 'LGPD_EXPORTACAO')
      union all
      select 'acesso:' || x.actor_id || ':' || to_char(now() at time zone e.fuso, 'YYYYMMDDHH24'), 'Mudança de permissões',
             coalesce(max(x.actor_email), 'Usuário') || ' alterou ' || count(*) || ' configuração(ões) de acesso'
        from eventos x where x.tabela in ('empresa_membros', 'departamento_membros', 'usuario_permissoes_extra', 'nivel_funcionalidades', 'departamento_niveis')
       group by x.actor_id
      union all
      select 'horario:' || x.actor_id || ':' || to_char(now() at time zone e.fuso, 'YYYYMMDD'), 'Atividade fora do horário',
             coalesce(max(x.actor_email), 'Usuário') || ' registrou atividade fora do horário (' || to_char(v_ini, 'HH24:MI') || '–' || to_char(v_fim, 'HH24:MI') || ')'
        from eventos x where (x.created_at at time zone e.fuso)::time not between v_ini and v_fim group by x.actor_id
    )
    insert into public.notificacoes (empresa_id, user_id, titulo, mensagem, link, chave)
    select e.id, m.user_id, al.titulo, left(al.msg, 300), '/auditoria', 'auditoria:' || al.chave
      from alertas al join public.empresa_membros m on m.empresa_id = e.id and m.ativo and m.admin_master
    on conflict (user_id, chave) where chave is not null do nothing;
    get diagnostics k = row_count; n := n + k;
  end loop;
  return n;
end $$;
revoke execute on function public.auditoria_alertas() from public, anon, authenticated;

-- ---------------------------------------------------------------------
-- Exclusão lógica (lixeira)
-- ---------------------------------------------------------------------
create or replace function public.exclusao_logica()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if current_setting('geeasy.exclusao_definitiva', true) = 'on' then
    return old; -- retenção / LGPD
  end if;
  execute format('update public.%I set excluido_em = now(), excluido_por = $1 where id = $2 and excluido_em is null', tg_table_name)
    using auth.uid(), old.id;
  return null;
end $$;
revoke execute on function public.exclusao_logica() from public, anon, authenticated;

do $$
declare t text;
begin
  foreach t in array array['clientes', 'processos', 'documentos', 'oportunidades'] loop
    execute format('alter table public.%I add column if not exists excluido_em timestamptz, add column if not exists excluido_por uuid references public.profiles(id) on delete set null', t);
    execute format('create index on public.%I (empresa_id, excluido_em) where excluido_em is not null', t);
    execute format('create policy %I on public.%I as restrictive for select to authenticated using (excluido_em is null)', t || '_nao_excluido', t);
    execute format('create trigger trg_exclusao_logica before delete on public.%I for each row execute function public.exclusao_logica()', t);
  end loop;
end $$;

-- registros excluídos não concedem acesso a filhos (documentos, interações, andamentos...)
create or replace function public.can_access_cliente(p_cliente uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.clientes c
     where c.id = p_cliente and c.empresa_id = public.empresa_atual() and c.excluido_em is null
       and (public.is_backoffice() or public.is_juridico() or c.consultor_id = auth.uid() or c.created_by = auth.uid())
  )
$$;

create or replace function public.can_access_processo(p_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.processos p
     where p.id = p_id and p.empresa_id = public.empresa_atual() and p.excluido_em is null and (
       public.has_role(array['admin','gestor','financeiro']::public.app_role[])
       or p.responsavel_id = auth.uid() or p.created_by = auth.uid() or auth.uid() = any(p.equipe)
       or public.is_membro_departamento(p.departamento_id)
     )
  )
$$;

create or replace function public.can_edit_processo(p_id uuid)
