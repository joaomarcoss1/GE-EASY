-- ---------------------------------------------------------------------
-- LGPD: a anonimização apaga DEFINITIVAMENTE os registros de documentos do titular (inclusive os da
-- lixeira) e devolve os caminhos no Storage para o servidor remover os arquivos.
-- ---------------------------------------------------------------------
drop function public.anonimizar_cliente(uuid);
create function public.anonimizar_cliente(p_cliente uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_rotulo text := 'Titular anonimizado ' || upper(substr(md5(p_cliente::text || clock_timestamp()::text), 1, 8));
  v_emp uuid := public.empresa_atual();
  v_caminhos text[];
begin
  if not public.tem_permissao('lgpd.anonimizar') then raise exception 'Somente administradores podem anonimizar titulares.'; end if;
  if not exists (select 1 from public.clientes where id = p_cliente and empresa_id = v_emp) then raise exception 'Cliente não encontrado.'; end if;
  if exists (select 1 from public.processos where cliente_id = p_cliente and status in ('ativo', 'suspenso') and excluido_em is null) then
    raise exception 'Há processos ativos deste cliente: encerre-os antes (guarda obrigatória dos dados).';
  end if;
  if exists (select 1 from public.contratos_honorarios where cliente_id = p_cliente and status = 'ativo') then
    raise exception 'Há contrato de honorários ativo deste cliente.';
  end if;
  update public.clientes set
    nome = v_rotulo, documento = null, rg = null, data_nascimento = null, email = null, telefone = null, whatsapp = null,
    cep = null, endereco = null, numero = null, complemento = null, bairro = null, profissao = null, renda_mensal = null,
    observacoes = null, tags = '{}', status = 'inativo', latitude = null, longitude = null, lgpd_consentimento_origem = null
  where id = p_cliente and empresa_id = v_emp;
  update public.atendimentos set nome_contato = v_rotulo, telefone = null, email = null, relato = null where cliente_id = p_cliente;
  update public.interacoes set descricao = '[conteúdo removido — anonimização LGPD]' where cliente_id = p_cliente;
  select coalesce(array_agg(storage_path) filter (where storage_path is not null), '{}') into v_caminhos
    from public.documentos where cliente_id = p_cliente and empresa_id = v_emp;
  perform set_config('geeasy.exclusao_definitiva', 'on', true);
  delete from public.documentos where cliente_id = p_cliente and empresa_id = v_emp;
  perform set_config('geeasy.exclusao_definitiva', 'off', true);
  return jsonb_build_object('rotulo', v_rotulo, 'caminhos', to_jsonb(v_caminhos));
end $$;
revoke execute on function public.anonimizar_cliente(uuid) from public, anon;
grant execute on function public.anonimizar_cliente(uuid) to authenticated;
