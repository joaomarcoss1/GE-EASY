create or replace function public.audit_trigger()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  v_old jsonb := case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) else null end;
  v_new jsonb := case when tg_op in ('INSERT','UPDATE') then to_jsonb(new) else null end;
  v_id text := coalesce(v_new->>'id', v_old->>'id', v_new->>'user_id', v_old->>'user_id', v_new->>'chave');
  v_tecnicos text[] := array['updated_at', 'datajud_sincronizado_em', 'datajud_atualizado_em', 'datajud_status', 'datajud_erro',
    'drive_folder_id', 'drive_file_id', 'drive_url', 'drive_status', 'drive_erro', 'drive_tentativas', 'drive_sincronizado_em',
    'drive_bloqueado_ate', 'google_event_id', 'last_seen_at'];
  v_acao text := tg_op;
  v_campos text[];
  v_ctx jsonb := public.contexto_requisicao();
begin
  v_old := v_old - 'access_token_enc' - 'refresh_token_enc';
  v_new := v_new - 'access_token_enc' - 'refresh_token_enc';
  if tg_op = 'UPDATE' then
    if (v_old - v_tecnicos) = (v_new - v_tecnicos) then
      return new;
    end if;
    select array_agg(k order by k) into v_campos from jsonb_object_keys(v_new) k
     where k <> all (v_tecnicos) and (v_new -> k) is distinct from (v_old -> k);
    if v_new ? 'excluido_em' then
      if v_old->>'excluido_em' is null and v_new->>'excluido_em' is not null then v_acao := 'EXCLUSAO';
      elsif v_old->>'excluido_em' is not null and v_new->>'excluido_em' is null then v_acao := 'RESTAURACAO';
      end if;
    end if;
  end if;
  insert into public.audit_logs (empresa_id, actor_id, actor_email, acao, tabela, registro_id, dados_antigos, dados_novos,
                                 campos_alterados, area, origem, ip, user_agent, request_id)
  values (coalesce((v_new->>'empresa_id')::uuid, (v_old->>'empresa_id')::uuid, public.empresa_atual()),
          auth.uid(), (select email from public.profiles where id = auth.uid()), v_acao, tg_table_name, v_id, v_old, v_new,
          v_campos, v_ctx->>'area', v_ctx->>'origem', v_ctx->>'ip', v_ctx->>'user_agent', v_ctx->>'request_id');
  return coalesce(new, old);
end $$;

create or replace function public.registrar_acesso(p_acao text, p_tabela text, p_registro text, p_detalhes jsonb default null)
returns void language plpgsql security definer set search_path = '' as $$
declare v_ctx jsonb := public.contexto_requisicao();
begin
  if auth.uid() is null then return; end if;
  if p_acao not in ('LOGIN', 'LOGOUT', 'LOGOUT_GLOBAL', 'DOWNLOAD', 'EXPORTACAO', 'IMPRESSAO', 'VISUALIZACAO_SIGILOSA', 'LGPD_EXPORTACAO',
                    'LGPD_ANONIMIZACAO', 'INTEGRACAO', 'TROCA_EMPRESA', 'TROCA_AREA', 'ACESSO_NEGADO', 'SIMULACAO') then
    raise exception 'ação de auditoria inválida';
  end if;
  if not public._rate_limit('acesso:' || auth.uid(), 600, 3600) then return; end if;
  insert into public.audit_logs (empresa_id, actor_id, actor_email, acao, tabela, registro_id, dados_novos, area, origem, ip, user_agent, request_id)
  values (public.empresa_atual(), auth.uid(), (select email from public.profiles where id = auth.uid()), p_acao, left(p_tabela, 60), left(p_registro, 100),
          case when pg_column_size(p_detalhes) < 4000 then p_detalhes end,
          v_ctx->>'area', v_ctx->>'origem', v_ctx->>'ip', v_ctx->>'user_agent', v_ctx->>'request_id');
end $$;

-- ---------------------------------------------------------------------
-- Selo por encadeamento de hash (por empresa). Ordem do encadeamento = selo_seq, atribuído na selagem
-- (eventos de transações que demoram a confirmar entram no próximo ciclo sem quebrar a cadeia).
-- ---------------------------------------------------------------------
create sequence public.audit_selo_seq;

create or replace function public.auditoria_conteudo(a public.audit_logs)
returns text language sql immutable set search_path = '' as $$
  select concat_ws('|', a.id, a.empresa_id, a.actor_id, a.actor_email, a.acao, a.tabela, a.registro_id, a.dados_antigos::text, a.dados_novos::text,
                   array_to_string(a.campos_alterados, ','), a.area, a.origem, a.ip, a.user_agent, a.request_id,
                   to_char(a.created_at at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US'))
$$;

create or replace function public.auditoria_selar(p_limite int default 5000, p_atraso interval default '30 seconds')
returns int language plpgsql security definer set search_path = '' as $$
declare r public.audit_logs; v_prev text; v_emp uuid; v_primeiro boolean := true; n int := 0; v_hash text;
begin
  if not pg_try_advisory_xact_lock(hashtext('geeasy.auditoria_selar')) then return 0; end if;
  perform set_config('geeasy.selando', 'on', true);
  for r in select * from public.audit_logs where hash is null and created_at <= now() - p_atraso
            order by empresa_id nulls first, id limit greatest(1, least(p_limite, 50000)) loop
    if v_primeiro or v_emp is distinct from r.empresa_id then
      select a.hash into v_prev from public.audit_logs a
       where a.empresa_id is not distinct from r.empresa_id and a.hash is not null order by a.selo_seq desc limit 1;
      v_emp := r.empresa_id;
      v_primeiro := false;
    end if;
    v_hash := encode(sha256(convert_to(coalesce(v_prev, '') || public.auditoria_conteudo(r), 'UTF8')), 'hex');
    update public.audit_logs set hash = v_hash, hash_anterior = v_prev, selo_seq = nextval('public.audit_selo_seq')
     where id = r.id and created_at = r.created_at;
    v_prev := v_hash;
    n := n + 1;
  end loop;
  perform set_config('geeasy.selando', 'off', true);
  return n;
end $$;
revoke execute on function public.auditoria_selar(int, interval) from public, anon, authenticated;

-- Verifica a cadeia da empresa ativa: recalcula cada selo e confere o elo com o anterior
create or replace function public.auditoria_verificar()
returns table (verificados bigint, pendentes bigint, adulterado_id bigint, integra boolean)
language plpgsql stable security definer set search_path = '' as $$
declare r public.audit_logs; v_prev text; v_n bigint := 0; v_primeiro boolean := true; v_emp uuid := public.empresa_atual();
begin
  if not public.tem_permissao('auditoria.view') then raise exception 'Sem permissão.' using errcode = '42501'; end if;
  for r in select * from public.audit_logs where empresa_id = v_emp and hash is not null order by selo_seq loop
    if (not v_primeiro and r.hash_anterior is distinct from v_prev)
       or r.hash <> encode(sha256(convert_to(coalesce(r.hash_anterior, '') || public.auditoria_conteudo(r), 'UTF8')), 'hex') then
      return query select v_n, (select count(*) from public.audit_logs where empresa_id = v_emp and hash is null), r.id, false;
      return;
    end if;
    v_prev := r.hash; v_primeiro := false; v_n := v_n + 1;
  end loop;
  return query select v_n, (select count(*) from public.audit_logs where empresa_id = v_emp and hash is null), null::bigint, true;
end $$;

-- Retenção (padrão 5 anos; configurável por empresa em configuracoes.auditoria.retencao_anos, mínimo 1)
create or replace function public.auditoria_retencao()
returns bigint language plpgsql security definer set search_path = '' as $$
declare n bigint := 0; k bigint; e record;
begin
  perform set_config('geeasy.retencao', 'on', true);
  for e in select em.id, greatest(1, coalesce((select (c.valor->>'retencao_anos')::int from public.configuracoes c where c.empresa_id = em.id and c.chave = 'auditoria'), 5)) as anos
             from public.empresas em loop
    delete from public.audit_logs where empresa_id = e.id and created_at < now() - make_interval(years => e.anos);
    get diagnostics k = row_count; n := n + k;
  end loop;
  perform set_config('geeasy.retencao', 'off', true);
  return n;
end $$;
revoke execute on function public.auditoria_retencao() from public, anon, authenticated;

