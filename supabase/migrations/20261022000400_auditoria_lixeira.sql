create or replace function public.lixeira_listar(p_tabela text default null)
returns table (tabela text, id uuid, titulo text, detalhe text, excluido_em timestamptz, excluido_por text)
language plpgsql stable security definer set search_path = '' as $$
declare v_emp uuid := public.empresa_atual();
begin
  if not public.tem_permissao('lixeira.gerir') then raise exception 'Sem permissão.' using errcode = '42501'; end if;
  return query
  select x.tabela, x.id, x.titulo, x.detalhe, x.excluido_em, p.full_name
    from (
      select 'clientes'::text as tabela, c.id, c.nome as titulo, c.documento as detalhe, c.excluido_em, c.excluido_por from public.clientes c where c.empresa_id = v_emp and c.excluido_em is not null
      union all
      select 'processos', p.id, p.titulo, p.numero_cnj, p.excluido_em, p.excluido_por from public.processos p where p.empresa_id = v_emp and p.excluido_em is not null
      union all
      select 'documentos', d.id, d.nome, d.categoria, d.excluido_em, d.excluido_por from public.documentos d where d.empresa_id = v_emp and d.excluido_em is not null
      union all
      select 'oportunidades', o.id, o.titulo, o.linha::text, o.excluido_em, o.excluido_por from public.oportunidades o where o.empresa_id = v_emp and o.excluido_em is not null
    ) x left join public.profiles p on p.id = x.excluido_por
   where p_tabela is null or x.tabela = p_tabela
   order by x.excluido_em desc
   limit 500;
end $$;

create or replace function public.lixeira_restaurar(p_tabela text, p_id uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare n int;
begin
  if not public.tem_permissao('lixeira.gerir') then raise exception 'Sem permissão.' using errcode = '42501'; end if;
  if p_tabela not in ('clientes', 'processos', 'documentos', 'oportunidades') then raise exception 'Tabela inválida.'; end if;
  execute format('update public.%I set excluido_em = null, excluido_por = null where id = $1 and empresa_id = $2 and excluido_em is not null', p_tabela)
    using p_id, public.empresa_atual();
  get diagnostics n = row_count;
  if n = 0 then raise exception 'Registro não encontrado na lixeira.'; end if;
end $$;

