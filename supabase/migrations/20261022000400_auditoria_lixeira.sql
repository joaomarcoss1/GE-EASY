-- GE EASY — Fase 2b: auditoria completa e exclusão lógica (lixeira)
--
-- * audit_logs particionada por mês, imutável (UPDATE/DELETE/TRUNCATE bloqueados) e selada por
--   encadeamento de hash (rotina a cada 5 min; verificação por empresa);
-- * cada evento guarda campos alterados, área, origem, IP, user-agent e request id;
-- * EXCLUSAO/RESTAURACAO como ações próprias; relatórios por funcionário e alertas;
-- * exclusão lógica em clientes, processos, documentos e oportunidades (DELETE vira lixeira).
