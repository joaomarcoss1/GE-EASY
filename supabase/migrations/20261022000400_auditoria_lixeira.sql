-- Imutável: só o selo (hash) pode ser gravado uma vez, pela rotina; exclusão só pela retenção
create or replace function public.auditoria_imutavel()
returns trigger language plpgsql set search_path = '' as $$
begin
  if tg_op = 'UPDATE' and current_setting('geeasy.selando', true) = 'on' and old.hash is null and new.hash is not null
     and (to_jsonb(new) - 'hash' - 'hash_anterior' - 'selo_seq') = (to_jsonb(old) - 'hash' - 'hash_anterior' - 'selo_seq') then
    return new;
  end if;
  if tg_op = 'DELETE' and current_setting('geeasy.retencao', true) = 'on' then
    return old;
  end if;
  raise exception 'A trilha de auditoria é imutável.' using errcode = '42501';
end $$;
revoke execute on function public.auditoria_imutavel() from public, anon, authenticated;
create trigger trg_audit_imutavel before update or delete on public.audit_logs for each row execute function public.auditoria_imutavel();
create trigger trg_audit_sem_truncate before truncate on public.audit_logs for each statement execute function public.auditoria_imutavel();

