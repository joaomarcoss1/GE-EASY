    select 1 from public.processos p
     where p.id = p_id and p.empresa_id = public.empresa_atual() and p.excluido_em is null and public.is_juridico() and (
       public.is_manager()
       or p.responsavel_id = auth.uid() or p.created_by = auth.uid() or auth.uid() = any(p.equipe)
