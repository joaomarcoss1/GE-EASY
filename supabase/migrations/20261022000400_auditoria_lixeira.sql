-- Partições mensais (as partições são tabelas próprias: RLS ligado e sem privilégios para a API)
create or replace function public.auditoria_criar_particoes(p_de date default null, p_meses_a_frente int default 3)
returns void language plpgsql security definer set search_path = '' as $$
declare v_ini date := date_trunc('month', coalesce(p_de, now()::date))::date; v_ate date := (date_trunc('month', now()) + make_interval(months => p_meses_a_frente))::date; v_nome text;
begin
  while v_ini <= v_ate loop
    v_nome := 'audit_logs_' || to_char(v_ini, 'YYYY_MM');
    if to_regclass('public.' || v_nome) is null then
      execute format('create table public.%I partition of public.audit_logs for values from (%L) to (%L)', v_nome, v_ini, (v_ini + interval '1 month')::date);
      execute format('alter table public.%I enable row level security', v_nome);
      execute format('revoke all on public.%I from anon, authenticated', v_nome);
    end if;
    v_ini := (v_ini + interval '1 month')::date;
  end loop;
end $$;
revoke execute on function public.auditoria_criar_particoes(date, int) from public, anon, authenticated;

